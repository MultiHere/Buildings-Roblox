"""Turn out/<name>/<name>.glb into Rojo-synced data modules that Studio builds into a textured MeshPart.

usage: python tools/to_roblox.py <name> [name...]
Writes studio/<name>/Mesh.luau (base64 float32/uint32 buffers) and Tex<i>.luau (base64 RGB, split in chunks),
read by studio/Import.luau through EditableMesh + EditableImage. Nothing is uploaded.
"""
import base64
import io
import json
import os
import struct
import sys

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
STUDS_PER_M = 1 / 0.28  # Roblox: 1 stud = 0.28 m
CHUNK = 900_000  # base64 chars per texture module


def read_glb(path):
    data = open(path, "rb").read()
    jlen = struct.unpack_from("<I", data, 12)[0]
    gj = json.loads(data[20:20 + jlen])
    bin_off = 20 + jlen + 8
    blob = data[bin_off:]

    def view(i):
        bv = gj["bufferViews"][i]
        o = bv.get("byteOffset", 0)
        return blob[o:o + bv["byteLength"]]

    def acc(i):
        a = gj["accessors"][i]
        n = {"SCALAR": 1, "VEC2": 2, "VEC3": 3}[a["type"]]
        dt = {5126: np.float32, 5125: np.uint32, 5123: np.uint16}[a["componentType"]]
        raw = view(a["bufferView"])[a.get("byteOffset", 0):]
        return np.frombuffer(raw, dt, a["count"] * n).reshape(a["count"], n) if n > 1 else \
            np.frombuffer(raw, dt, a["count"])

    prim = gj["meshes"][0]["primitives"][0]
    at = prim["attributes"]
    img = Image.open(io.BytesIO(view(gj["images"][0]["bufferView"]))).convert("RGB")
    return acc(at["POSITION"]), acc(at["NORMAL"]), acc(at["TEXCOORD_0"]), acc(prim["indices"]).astype(np.uint32), img


def b64(a):
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode()


def main(name):
    P, N, UV, I, img = read_glb(os.path.join(ROOT, "out", name, f"{name}.glb"))
    P = P * STUDS_PER_M
    # MeshParts built from an EditableMesh keep the mesh origin at the part centre: centre the bounds
    P = P - (P.min(0) + P.max(0)) / 2
    d = os.path.join(ROOT, "studio", "creatures", name)
    os.makedirs(d, exist_ok=True)
    # overwrite in place: deleting files under a running `rojo serve` crashes it
    with open(os.path.join(d, "Mesh.luau"), "w", newline="\n") as f:
        f.write(f"-- generated by tools/to_roblox.py from out/{name}/{name}.glb\nreturn {{\n"
                f"\tverts = {len(P)}, tris = {len(I) // 3}, texSize = {img.size[0]},\n"
                f'\tpos = "{b64(P.astype("<f4"))}",\n\tnrm = "{b64(N.astype("<f4"))}",\n'
                f'\tuv = "{b64(UV.astype("<f4"))}",\n\tidx = "{b64(I.astype("<u4"))}",\n}}\n')
    # detail-baked maps (tools/bake.py) when present: crease-darkened colour + an OpenGL normal map
    detail = os.path.join(ROOT, "out", name, f"{name}_albedo_detail.png")
    normal = os.path.join(ROOT, "out", name, f"{name}_normal.png")
    if os.path.exists(detail):
        img = Image.open(detail).convert("RGB")
    maps = [("Tex", img)] + ([("Nrm", Image.open(normal).convert("RGB"))] if os.path.exists(normal) else [])
    for prefix, im in maps:
        tex = b64(np.asarray(im.resize(img.size), np.uint8))
        parts = [tex[i:i + CHUNK] for i in range(0, len(tex), CHUNK)]
        for k, s in enumerate(parts, 1):
            with open(os.path.join(d, f"{prefix}{k}.luau"), "w", newline="\n") as f:
                f.write(f'return "{s}"\n')
    print(f"{name}: {len(P)} verts, {len(I) // 3} tris, tex {img.size}, maps {[m[0] for m in maps]}, "
          f"height {P[:, 1].max() - P[:, 1].min():.2f} studs")


if __name__ == "__main__":
    for n in sys.argv[1:]:
        main(n)
